#!/usr/bin/env node
// Reads the built surface files out of a dist dir and writes the module the
// zone Worker serves them from. Bytes are carried as base64 so parity with
// dist/ is exact. Usage: generate-surfaces.mjs [distDir] [outFile]
// (or SURFACES_DIST / SURFACES_OUT).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SURFACE_PATHS, contentTypeFor } from '../worker/surfaces.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = resolve(process.argv[2] ?? process.env.SURFACES_DIST ?? join(root, 'dist'));
const out = resolve(process.argv[3] ?? process.env.SURFACES_OUT ?? join(root, 'worker/surfaces.generated.js'));

const entries = SURFACE_PATHS.map((path) => {
  const file = join(dist, path.slice(1));
  if (!existsSync(file)) {
    throw new Error(`missing surface ${path} in ${dist} — run \`npm run build\` first`);
  }
  return `  ${JSON.stringify(path)}: { type: ${JSON.stringify(contentTypeFor(path))}, b64: ${JSON.stringify(readFileSync(file).toString('base64'))} },`;
});

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// Generated by scripts/generate-surfaces.mjs — do not edit.\nexport default {\n${entries.join('\n')}\n};\n`);
console.log(`wrote ${out} (${SURFACE_PATHS.length} surfaces from ${dist})`);
